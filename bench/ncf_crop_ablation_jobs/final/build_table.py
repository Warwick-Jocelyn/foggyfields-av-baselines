#!/usr/bin/env python3
"""Build the per-clip result tables of RESULTS_BASELINES.md from the metric JSONs (nothing typed by hand).

  python3 build_table.py [--root $BW] [--clips NFF-02 NFF-08 NFF-10] [--write RESULTS_BASELINES.md]

Rows: results_final/{allfix,opreg5e4}/metrics (SplatAD), results_final/std (NeuRAD, EmerNeRF, UniSim), results_final/v13 (V1.3 lanes).
RGB = primary safe_crop numbers of eval_common_region.py; LiDAR = cd_returns_m / cd2_returns_m2 / depth_median_l2_returns_m
(returns_only protocol) of the lidar JSON; GPU wall = train / (render + metrics + lidar) seconds from timings*.csv.
--write replaces everything between the '## Results' and '## Commands and paths' headings of the report.
"""
import argparse, csv, json, re, sys
from pathlib import Path


def load(p):
    try:
        return json.loads(Path(p).read_text())
    except Exception:
        return None


def timings(res_root, method, clip, label=None):
    tr = ev = 0.0
    for f in Path(res_root).glob("timings*.csv"):
        with open(f) as fh:
            for r in csv.DictReader(fh):
                if label is not None:
                    if r.get("label") != label or r.get("clip") != clip:
                        continue
                elif r.get("method") != method or r.get("clip") != clip:
                    continue
                s = float(r.get("seconds") or 0)
                if r.get("stage") == "train":
                    tr += s
                elif r.get("stage") in ("render", "metrics", "lidar_dump", "lidar_metrics", "lidar", "lidar_eval"):
                    ev += s
    return tr, ev


def fmt(v, nd=3):
    return "n/a" if v is None else f"{v:.{nd}f}"


def row(name, met, lid, iters, tr, ev, met_p, lid_p):
    pr = (met or {}).get("primary", {})
    n = (met or {}).get("n_images")
    wall = f"{tr / 3600:.2f} h / {ev / 60:.0f} min" if (tr or ev) else "n/a"
    cd = (lid or {}).get("cd_returns_m"); cd2 = (lid or {}).get("cd2_returns_m2"); dm = (lid or {}).get("depth_median_l2_returns_m")
    pts = (lid or {}).get("n_gt")
    js = " ".join(f"`{Path(p).name}`" for p in (met_p, lid_p) if p and Path(p).is_file()) or "n/a"
    return (f"| {name} | {iters or 'n/a'} | {wall} | {fmt(pr.get('psnr'), 2)} | {fmt(pr.get('ssim'))} | {fmt(pr.get('lpips'))} | "
            f"{n if n is not None else 'n/a'} | {fmt(cd)} | {fmt(cd2, 2)} | {fmt(dm)} | {pts if pts else 'n/a'} | {js} |")


HEAD = ("| row | iters | GPU wall (train / render+eval) | PSNR ↑ | SSIM ↑ | LPIPS ↓ | n img | LiDAR CD (m) ↓ | CD² (m²) ↓ | "
        "depth med L2 (m) ↓ | points kept | metric JSONs |\n|---|---|---|---|---|---|---|---|---|---|---|---|")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=Path("/capstor/scratch/cscs/yitiwang/ncf-crop-ablation"))
    ap.add_argument("--clips", nargs="+", default=["NFF-02", "NFF-08", "NFF-10"])
    ap.add_argument("--write", type=Path, default=None)
    a = ap.parse_args()
    R = a.root / "results_final"
    out = []
    for clip in a.clips:
        rows = []
        for tag, name in (("allfix", "SplatAD allfix (opacity reg 5e-4 + F1b/F2b)"), ("opreg5e4", "SplatAD opreg5e4 (fallback, pre-fix data path)")):
            mp, lp = R / tag / "metrics" / f"metrics_splatad__safe__{clip}.json", R / tag / "lidar" / f"lidar_splatad_safe__{clip}.json"
            m, l = load(mp), load(lp)
            if m or l:
                rows.append(row(name, m, l, (m or {}).get("iters") or 30000, *timings(R / tag, "splatad", clip), mp, lp))
        for meth, name, it in (("neurad", "NeuRAD standard (30k, corrected bench)", 30000), ("emernerf", "EmerNeRF (corrected bench, 30k)", 30000), ("unisim", "UniSim (corrected bench, no ray drop, 30k schedule)", 30000)):
            mp, lp = R / "std" / "metrics" / f"metrics_{meth}__safe__{clip}.json", R / "std" / "lidar" / f"lidar_{meth}_safe__{clip}.json"
            m, l = load(mp), load(lp)
            if m or l:
                rows.append(row(name, m, l, (m or {}).get("iters") or it, *timings(R / "std", meth, clip), mp, lp))
        for mp in sorted((R / "v13" / "metrics").glob(f"metrics_v13__*__{clip}.json")) if (R / "v13" / "metrics").is_dir() else []:
            label = re.sub(r"^metrics_v13__(.*)__" + clip + r"\.json$", r"\1", mp.name)
            lp = R / "v13" / "lidar" / f"lidar_v13__{label}__{clip}.json"
            m, l = load(mp), load(lp)
            rows.append(row(f"FoggyField V1.3 {label} (5k; oracle drop)", m, l, (m or {}).get("iters") or 5000, *timings(R / "v13", "", clip, label=label), mp, lp))
        out.append(f"### {clip}\n{HEAD}\n" + ("\n".join(rows) if rows else "| _(no finished run yet)_ |") + "\n")
    text = "## Results\n_(generated by jobs/final/build_table.py from the metric JSONs; n/a = stage not finished)_\n\n" + "\n".join(out)
    if a.write:
        s = a.write.read_text()
        i, j = s.index("## Results"), s.index("## Commands and paths")
        a.write.write_text(s[:i] + text + "\n" + s[j:])
        print(f"updated {a.write}")
    else:
        print(text)


if __name__ == "__main__":
    sys.exit(main())
